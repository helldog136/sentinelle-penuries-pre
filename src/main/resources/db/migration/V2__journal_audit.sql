-- V2 : journal d'audit.
-- Journal append-only par conception : aucun UPDATE ni DELETE ne doit exister dans le code.
-- Le chaînage de hachage (SHA-256) est calculé par l'adaptateur d'audit, pas par la base.
-- Pas de clé étrangère sur rupture_id : le journal survit à tout (y compris à la suppression d'une rupture).
-- Pas de trigger (non portable entre H2 et PostgreSQL).

CREATE TABLE journal_audit (
    sequence        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evenement_id    UUID                     NOT NULL,
    type_evenement  VARCHAR(20)              NOT NULL,
    rupture_id      UUID                     NOT NULL,
    acteur_sujet    VARCHAR(128)             NOT NULL,
    acteur_role     VARCHAR(20)              NOT NULL,
    instant         TIMESTAMP WITH TIME ZONE NOT NULL,
    resume          VARCHAR(500)             NOT NULL,
    hash_precedent  CHAR(64)                 NOT NULL,
    hash_courant    CHAR(64)                 NOT NULL,
    CONSTRAINT uq_journal_audit_evenement UNIQUE (evenement_id),
    CONSTRAINT uq_journal_audit_hash_courant UNIQUE (hash_courant),
    CONSTRAINT ck_journal_audit_type CHECK (type_evenement IN ('DECLARATION', 'MODIFICATION', 'CLOTURE'))
);

CREATE INDEX idx_journal_audit_rupture ON journal_audit (rupture_id);
